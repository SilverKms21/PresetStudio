fn table(lang: Lang) -> &'static HashMap<&'static str, &'static str> {
    static EN_MAP: OnceLock<HashMap<&'static str, &'static str>> = OnceLock::new();
    static PT_MAP: OnceLock<HashMap<&'static str, &'static str>> = OnceLock::new();
    match lang {
        Lang::En => EN_MAP.get_or_init(|| EN.iter().copied().collect()),
        Lang::Pt => PT_MAP.get_or_init(|| PT.iter().copied().collect()),
    }
}

/// Translate `key` (falls back to English, then to the key itself).
pub fn tr(lang: Lang, key: &str) -> String {
    table(lang)
        .get(key)
        .or_else(|| table(Lang::En).get(key))
        .map(|s| s.to_string())
        .unwrap_or_else(|| key.to_string())
}

/// Translate and substitute `{name}` placeholders. `{{` / `}}` become literal braces.
pub fn trf(lang: Lang, key: &str, args: &[(&str, String)]) -> String {
    let mut text = tr(lang, key);
    for (name, value) in args {
        text = text.replace(&format!("{{{}}}", name), value);
    }
    text.replace("{{", "{").replace("}}", "}")
}
